import {
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import { writeCompiledDistributionNotices } from "../distribution/compiled-notices";
import { writeNativeDistributionNotices } from "../distribution/native-notices";
import {
  readDistributionNotices,
  writeDistributionNotices,
} from "../distribution/notices";
import { writeRuntimeDistributionNotices } from "../distribution/runtime-notices";
import { isMain } from "../is-main";

const root = resolve(import.meta.dir, "../..");
const app = join(root, "apps/lite");
const build = join(app, "build");
const nativeInput = join(build, "native-input");
const native = join(nativeInput, "apps/desktop/src-tauri");
const desktop = join(root, "apps/desktop/src-tauri");
const target = resolve(process.env.CARGO_TARGET_DIR ?? join(native, "target"));

async function run(cmd: string[], cwd = root, timeout = 240_000) {
  const child = Bun.spawn({
    cmd,
    cwd,
    stdin: "ignore",
    stderr: "inherit",
    stdout: "inherit",
    windowsHide: true,
  });
  const limit = setTimeout(() => child.kill(), timeout);
  try {
    if ((await child.exited) !== 0)
      throw Error("Lite build step failed: " + cmd.slice(0, 3).join(" "));
  } finally {
    clearTimeout(limit);
  }
}

async function main() {
  if (process.platform !== "win32" || process.arch !== "x64")
    throw Error("Lite portable builds require Windows x64.");
  await run([process.execPath, "run", "lite:web:build"]);
  mkdirSync(join(native, "src"), { recursive: true });
  mkdirSync(join(native, "icons"), { recursive: true });
  // Both products use one locked native dependency graph. Only this crate's
  // main, ACL, application identity and frontend are included in the Lite exe.
  const cargo = readFileSync(join(desktop, "Cargo.toml"), "utf8");
  writeFileSync(
    join(native, "Cargo.toml"),
    cargo + '\n[[bin]]\nname = "agent-forge-lite"\npath = "src/main.rs"\n',
  );
  copyFileSync(join(desktop, "Cargo.lock"), join(native, "Cargo.lock"));
  copyFileSync(
    join(desktop, "src/workspace.rs"),
    join(native, "src/workspace.rs"),
  );
  for (const [source, destination] of [
    ["main.rs", "src/main.rs"],
    ["build.rs", "build.rs"],
    ["tauri.conf.json", "tauri.conf.json"],
    ["icons/icon.ico", "icons/icon.ico"],
  ] as const)
    copyFileSync(join(app, "src-tauri", source), join(native, destination));
  const embedded = join(nativeInput, "apps/desktop/dist");
  // This directory is generated by this command. A stale hashed JS chunk
  // must never survive the next native embed.
  if (existsSync(embedded)) {
    if (realpathSync.native(embedded) !== embedded)
      throw Error("Refusing a redirected Lite asset directory.");
    rmSync(embedded, { recursive: true });
  }
  cpSync(join(app, "dist"), embedded, { recursive: true });

  const scratch = mkdtempSync(join(build, "portable-"));
  let published = false;
  try {
    const graphs = [];
    for (const [name, entry] of [
      ["desktop-host", "reader-entry"],
      ["hearth", "tracker-entry"],
    ] as const) {
      const graph = join(build, name + ".graph.json");
      await run([
        process.execPath,
        "build",
        "--compile",
        "--no-compile-autoload-dotenv",
        "--no-compile-autoload-bunfig",
        "scripts/lite/" + entry + ".ts",
        "--metafile=" + graph,
        "--outfile",
        join(scratch, name + ".exe"),
      ]);
      graphs.push({ name, path: graph });
    }
    await run(
      [
        "cargo",
        "build",
        "--locked",
        "--release",
        "--features",
        "tauri/custom-protocol",
        "--bin",
        "agent-forge-lite",
      ],
      native,
      900_000,
    );
    copyFileSync(
      join(target, "release/agent-forge-lite.exe"),
      join(scratch, "agent-forge-lite.exe"),
    );
    copyFileSync(
      join(root, ".forge-desktop-source.json"),
      join(scratch, ".forge-desktop-source.json"),
    );
    writeDistributionNotices(scratch, await readDistributionNotices(root));
    await writeNativeDistributionNotices(scratch, nativeInput);
    writeRuntimeDistributionNotices(scratch, root);
    writeCompiledDistributionNotices(scratch, root, graphs);
    const stage = join(build, "windows-x64");
    const old = stage + "-previous-" + crypto.randomUUID();
    if (existsSync(stage)) renameSync(stage, old);
    try {
      renameSync(scratch, stage);
    } catch (error) {
      if (existsSync(old)) renameSync(old, stage);
      throw error;
    }
    published = true;
    if (existsSync(old)) rmSync(old, { recursive: true });
    console.log(
      JSON.stringify({
        ok: true,
        data: { executable: join(stage, "agent-forge-lite.exe") },
        error: null,
      }),
    );
  } finally {
    if (!published && existsSync(scratch)) rmSync(scratch, { recursive: true });
  }
}
if (isMain(import.meta)) {
  const args = process.argv.slice(2);
  const open = args[0] === "--open";
  if (
    args.length &&
    !(
      open &&
      (args.length === 1 || (args.length === 3 && args[1] === "--root"))
    )
  ) {
    throw Error("Use lite:build, or lite:dev [--root <harness checkout>].");
  }
  await main();
  if (open) {
    const stage = join(build, "windows-x64");
    const child = Bun.spawn(
      [join(stage, "agent-forge-lite.exe"), ...args.slice(1)],
      {
        cwd: stage,
        stdin: "ignore",
        stdout: "ignore",
        stderr: "ignore",
        windowsHide: true,
      },
    );
    child.unref();
  }
}
